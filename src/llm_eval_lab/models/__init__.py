"""Frozen contract layer: the pure domain models every other layer depends on.

This package imports pydantic and the standard library, and nothing else. It
knows nothing of SQLAlchemy, FastAPI, Typer, httpx or any vendor SDK, which is
what lets a test construct any contract object without a database, a server or
a network. ``tests/unit/test_contract_purity.py`` enforces that mechanically.

Every public contract name is re-exported here. Consumers import from
``llm_eval_lab.models``, never from a submodule path, so a later reorganization
of the submodules is invisible to them. ``__all__`` is checked against the
literal expected surface in ``tests/unit/test_contract_surface.py`` in both
directions, so neither a removal nor an unplanned addition can pass unnoticed.
"""

